const dicts: Record<Lang, Dict> = { uk, en, ru };
let current: Lang = "uk";

export const LANGS: Array<{ id: Lang; label: string }> = [
  { id: "uk", label: "Українська" },
  { id: "en", label: "English" },
  { id: "ru", label: "Русский" },
];

export function setLang(lang: Lang) {
  current = dicts[lang] ? lang : "uk";
  document.documentElement.lang = current;
}

export function getLang(): Lang {
  return current;
}

export function t(key: StringKey, params?: Record<string, string | number>): string {
  let s = dicts[current][key] ?? uk[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function agoText(ts: number | null, nowMs = Date.now()): string {
  if (!ts) return t("never");
  const min = Math.floor((nowMs - ts) / 60000);
  if (min < 1) return t("justNow");
  if (min < 60) return t("minAgo", { n: min });
  return t("hoursAgo", { n: Math.floor(min / 60) });
}

/** Spoken form of a countdown: "2 год 14 хв" instead of "2:14". */
export function durationText(minutes: number): string {
  const total = Math.max(0, Math.ceil(minutes - 1e-6));
  const h = Math.floor(total / 60);
  const m = total % 60;
  return h ? t("durationHm", { h, m }) : t("durationM", { m });
}

